// Packs models/<boat>.glb into models/models.js so the wallpaper can load them when it is
// opened straight from disk (file://), where browsers block fetching neighbouring files.
//
//   node tools/pack-models.mjs
//
// Boat names: yacht, galleon, fishing, sailboat. Run it again whenever you add or replace a model.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'models');
const BOATS = ['yacht', 'galleon', 'fishing', 'sailboat'];
const lines = ['// Generated by tools/pack-models.mjs. Do not edit by hand.', 'window.OCEAN_MODELS = window.OCEAN_MODELS || {};'];
let total = 0;
for (const file of readdirSync(dir)) {
  const m = file.match(/^(.+)\.glb$/i);
  if (!m) continue;
  if (!BOATS.includes(m[1])) { console.warn(`skipping ${file}: name it one of ${BOATS.join(', ')}.glb`); continue; }
  const buf = readFileSync(join(dir, file));
  if (buf.readUInt32LE(0) !== 0x46546c67) { console.warn(`skipping ${file}: not a binary glTF (.glb)`); continue; }
  lines.push(`window.OCEAN_MODELS[${JSON.stringify(m[1])}] = ${JSON.stringify(buf.toString('base64'))};`);
  total += buf.length;
  console.log(`packed ${file} (${(buf.length / 1e6).toFixed(1)} MB)`);
}
writeFileSync(join(dir, 'models.js'), lines.join('\n') + '\n');
console.log(`wrote models/models.js (${(total / 1e6).toFixed(1)} MB of models)`);
if (total > 60e6) console.warn('that is large; consider compressing the models (see README)');
